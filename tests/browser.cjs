// Run with QWEROS_PLAYWRIGHT pointing to an installed playwright package.
const { chromium } = require(process.env.QWEROS_PLAYWRIGHT || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true});
  const errors = [];
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  page.on('pageerror', e=>errors.push(e.message));
  const base = process.env.QWEROS_BASE_URL || 'http://127.0.0.1:8015';
  await page.goto(base + '/');
  await page.locator('.identity-widget h1').waitFor();
  assert.match(await page.locator('.identity-widget').innerText(), /資深產品經理/);
  await page.locator('.window-control--close[data-window-id="welcome"]').click();
  await page.locator('.dock-item[data-app-id="projects"]').click();
  assert.match(page.url(), /\/projects$/);
  await page.locator('.window[data-window-id="projects"] [data-action="open-project-detail"][data-project-slug="healthcare-ai"]').first().click();
  assert.match(page.url(), /\/projects\/healthcare-ai$/);
  assert.equal(await page.locator('.window[data-window-id="project-detail"]').count(),0);
  await page.goBack();
  assert.match(page.url(), /\/projects$/);
  await page.goForward();
  assert.match(await page.locator('.window[data-window-id="projects"]').innerText(), /Healthcare AI Assistant/);
  await page.locator('.dock-item[data-app-id="about"]').click();
  await page.locator('.window-control--minimize[data-window-id="about"]').click();
  assert.match(page.url(), /\/projects\/healthcare-ai$/);
  await page.locator('.window-control--close[data-window-id="projects"]').click();
  assert.equal(new URL(page.url()).pathname,'/');
  await page.waitForFunction(()=>document.activeElement.dataset.appId === 'projects');
  await page.locator('.dock-item[data-app-id="resume"]').click();
  assert.equal(await page.locator('[data-theme-select] option').count(),3);
  assert.equal(await page.locator('html').getAttribute('data-theme'),'ivory');
  const resize = page.locator('.window[data-window-id="resume"] .window-resize-handle');
  const box = await resize.boundingBox();
  await page.mouse.move(box.x+10,box.y+10); await page.mouse.down(); await page.mouse.move(box.x-80,box.y-60); await page.mouse.up();
  const geometry = await page.evaluate(()=>JSON.parse(localStorage.getItem('qweros-geometry-v2-ivory')).resume);
  await page.reload();
  const actual = await page.locator('.window[data-window-id="resume"]').boundingBox();
  assert.equal(Math.round(actual.width), Math.round(geometry.size.width));
  await page.locator('[data-theme-select]').selectOption('midnight');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'midnight');
  assert.match(page.url(), /\/resume$/);
  assert.equal(await page.evaluate(()=>localStorage.getItem('qweros-theme')),'midnight');
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'midnight');
  await page.locator('[data-theme-select]').selectOption('jade');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'jade');
  assert.match(page.url(), /\/resume$/);
  await page.locator('.locale-toggle').click();
  await page.waitForURL(/\/en\/resume\/?$/);
  assert.equal(await page.locator('html').getAttribute('lang'), 'en');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'jade');
  assert.match(await page.locator('.window[data-window-id="resume"]').innerText(), /Senior Product Manager/);
  await page.keyboard.press('Control+k');
  await page.waitForFunction(()=>document.activeElement.id === 'spotlight-input');
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.evaluate(()=>document.activeElement.classList.contains('spotlight-result')),true);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>document.activeElement.dataset.action),'toggle-spotlight');
  await page.locator('.dock-item[data-app-id="terminal"]').click();
  await page.locator('#terminal-input').fill('whoami');
  await page.locator('#terminal-input').press('Enter');
  assert.match(await page.locator('.terminal-output').innerText(), /Senior Product Manager/);
  await page.locator('#terminal-input').fill('open projects');
  await page.locator('#terminal-input').press('Enter');
  await page.waitForURL(/\/en\/projects$/);
  await page.screenshot({path:'/tmp/qweros-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.goto(base+'/projects/healthcare-ai/');
  assert.equal(await page.locator('.mobile-app-screen .project-detail-content').isVisible(),true);
  await page.locator('.mobile-back').click();
  assert.match(page.url(), /\/projects$/);
  await page.screenshot({path:'/tmp/qweros-mobile.png'});
  for(const route of ['about','resume','projects','contact']) {
    const nojs = await browser.newContext({javaScriptEnabled:false});
    const staticPage = await nojs.newPage();
    for (const prefix of ['', 'en/']) {
      const response = await staticPage.goto(`${base}/${prefix}${route}/`);
      assert.equal(response.status(),200);
      const text = await staticPage.locator('main').innerText();
      assert.ok(text.length > (route === 'contact' ? 120 : 350));
      if (route === 'contact') assert.equal(await staticPage.locator('a[href="mailto:qwerboy@gmail.com"]').count(),1);
      assert.equal(await staticPage.locator('link[hreflang]').count(),3);
    }
    await nojs.close();
  }
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('PASS: desktop routes/history/focus/resize/reload/theme/locale/spotlight, mobile detail/back, 8 no-JS core pages');
})().catch(e=>{console.error(e);process.exit(1)});
